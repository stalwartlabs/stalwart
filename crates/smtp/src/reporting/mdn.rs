use crate::{
    core::{Session, SessionAddress, SessionData},
    inbound::dkim::DkimSign,
    outbound::local::AutogeneratedSigner,
    queue::{
        MessageSource,
        quota::HasQueueQuota,
        spool::{QueueOutcome, QueueParams, SmtpSpool},
    },
};
use common::{
    Server,
    auth::AccountInfo,
    network::{ServerInstance, stream::NullIo},
};
use std::sync::Arc;

pub struct MdnSender {
    session: Box<Session<NullIo>>,
}

pub enum MdnOutcome {
    RateLimited,
    Queue(QueueOutcome),
}

impl MdnSender {
    pub fn new(
        server: Server,
        instance: Arc<ServerInstance>,
        account: AccountInfo,
        from_address: &str,
        session_id: u64,
    ) -> Self {
        MdnSender {
            session: Box::new(Session::local(
                server,
                instance,
                SessionData::local(
                    account,
                    Some(SessionAddress::new(from_address.to_string())),
                    vec![],
                    vec![],
                    session_id,
                ),
            )),
        }
    }

    pub fn owns_address(&self, address: &str) -> bool {
        self.session
            .authenticated_emails()
            .iter()
            .any(|owned| owned.eq_ignore_ascii_case(address))
    }

    pub async fn send(
        &mut self,
        from_address: &str,
        recipients: &[String],
        raw_message: &[u8],
    ) -> MdnOutcome {
        let session = self.session.as_mut();
        session.data.rcpt_to.clear();
        if !session.is_allowed().await {
            return MdnOutcome::RateLimited;
        }
        for rcpt in recipients {
            session.data.rcpt_to.push(SessionAddress::new(rcpt.clone()));
            if !session.is_allowed().await {
                return MdnOutcome::RateLimited;
            }
        }

        let server = &session.server;
        let session_id = session.data.session_id;
        let mut message = server.new_message("", MessageSource::Autogenerated, session_id);
        for rcpt in recipients {
            message.expand_and_add_recipient(rcpt, server).await;
        }
        if message.message.recipients.is_empty() {
            return MdnOutcome::Queue(QueueOutcome::Failed);
        }
        message.message.size = raw_message.len() as u64;

        let quotas = server.queue_quotas(&message).await;
        let dkim_signers = server
            .eval_signers(
                &server.core.sieve.untrusted_sign,
                &AutogeneratedSigner {
                    message: &message.message,
                    account_address: from_address,
                },
                session_id,
            )
            .await;

        MdnOutcome::Queue(
            message
                .queue(
                    QueueParams::new(raw_message, session_id, server)
                        .with_dkim_signers(dkim_signers)
                        .with_quotas(quotas),
                )
                .await,
        )
    }
}
