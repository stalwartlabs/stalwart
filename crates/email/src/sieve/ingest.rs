struct SieveMessage<'x> {
    pub raw_message: Cow<'x, [u8]>,
    pub file_into: Vec<u32>,
    pub did_file_into: bool,
    pub flags: Vec<Keyword>,
}

struct SieveHandler<'x, 'r> {
    server: &'x Server,
    session_id: u64,
    script_hash: u32,
    cache: Option<Arc<MessageStoreCache>>,
    resolved: Vec<(MailboxQuery, Option<u32>)>,
    has_mailboxes: bool,
    mail_from: &'x str,
    server_name: &'x str,
    mail_max_size: usize,
    max_received_headers: usize,
    received_headers: usize,
    messages: Vec<SieveMessage<'r>>,
    autogenerated: Vec<AutogeneratedMessage>,
    checked_ids: AHashMap<SeenIdHash, bool>,
    seen_ids: Vec<SeenId>,
    reject_reason: Option<String>,
    do_discard: bool,
    do_deliver: bool,
    do_redirect: bool,
    redirect_copies: usize,
    pending: Option<PendingWork<'x>>,
}

enum PendingWork<'x> {
    Include {
        name: String,
    },
    DuplicateId {
        hash: SeenIdHash,
        expiry: u64,
        last: bool,
    },
    Function {
        id: u32,
        arguments: Vec<Variable<'x>>,
    },
    MailboxExists(MailboxExistsRequest),
    FileInto(FileIntoRequest),
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum MailboxQuery {
    Path(Box<str>),
    Role(SpecialUse),
    Id(u32),
}

struct MailboxExistsRequest {
    mailboxes: Vec<Option<MailboxQuery>>,
    roles: Vec<Option<MailboxQuery>>,
}

struct FileIntoRequest {
    path: MailboxQuery,
    mailbox_id: Option<MailboxQuery>,
    special_use: Option<MailboxQuery>,
    create: bool,
    flags: Vec<Keyword>,
    message_id: usize,
}

enum FileIntoTarget {
    Mailbox(u32),
    Create,
}

enum Unresolved<'x> {
    Query(&'x MailboxQuery),
    Cache,
}

impl MailboxQuery {
    fn from_id(id: &str) -> Option<Self> {
        Id::from_str(id)
            .ok()
            .map(|id| MailboxQuery::Id(id.document_id()))
    }

    fn from_role(role: &str) -> Option<Self> {
        SpecialUse::parse_use_attr(role).map(MailboxQuery::Role)
    }

    async fn resolve(&self, server: &Server, account_id: u32) -> trc::Result<Option<u32>> {
        match self {
            MailboxQuery::Path(path) => server.mailbox_id_by_path(account_id, path).await,
            MailboxQuery::Role(role) => server.mailbox_id_by_role(account_id, *role).await,
            MailboxQuery::Id(id) => server
                .mailbox_id_exists(account_id, *id)
                .await
                .map(|exists| exists.then_some(*id)),
        }
    }
}

impl SieveHandler<'_, '_> {
    fn answer(&self, query: &MailboxQuery) -> Option<Option<u32>> {
        match query {
            MailboxQuery::Role(SpecialUse::Inbox) => return Some(Some(INBOX_ID)),
            MailboxQuery::Role(SpecialUse::Trash) => return Some(Some(TRASH_ID)),
            _ => {}
        }

        match &self.cache {
            Some(cache) => Some(match query {
                MailboxQuery::Path(path) => cache.mailbox_by_path(path).map(|m| m.document_id),
                MailboxQuery::Role(role) => cache.mailbox_by_role(role).map(|m| m.document_id),
                MailboxQuery::Id(id) => cache.has_mailbox_id(id).then_some(*id),
            }),
            None => self
                .resolved
                .iter()
                .find(|(resolved, _)| resolved == query)
                .map(|(_, document_id)| *document_id),
        }
    }

    fn mailbox_exists_answer<'q>(
        &self,
        request: &'q MailboxExistsRequest,
    ) -> Result<bool, &'q MailboxQuery> {
        let mut roles = Vec::with_capacity(request.roles.len());
        for role in &request.roles {
            roles.push(match role {
                Some(query) => self.answer(query).ok_or(query)?.unwrap_or(u32::MAX),
                None => u32::MAX,
            });
        }

        if !request.mailboxes.is_empty() {
            for mailbox in &request.mailboxes {
                let document_id = match mailbox {
                    Some(query) => self.answer(query).ok_or(query)?,
                    None => None,
                };
                if !document_id
                    .is_some_and(|document_id| roles.is_empty() || roles.contains(&document_id))
                {
                    return Ok(false);
                }
            }
            Ok(true)
        } else {
            Ok(!roles.is_empty() && !roles.contains(&u32::MAX))
        }
    }

    fn file_into_target<'q>(
        &self,
        request: &'q FileIntoRequest,
    ) -> Result<FileIntoTarget, Unresolved<'q>> {
        for query in [&request.mailbox_id, &request.special_use]
            .into_iter()
            .flatten()
        {
            if let Some(document_id) = self.answer(query).ok_or(Unresolved::Query(query))? {
                return Ok(FileIntoTarget::Mailbox(document_id));
            }
        }

        if request.create {
            let Some(cache) = &self.cache else {
                return Err(Unresolved::Cache);
            };
            let MailboxQuery::Path(path) = &request.path else {
                return Ok(FileIntoTarget::Mailbox(INBOX_ID));
            };
            Ok(cache
                .mailbox_by_folded_path(path)
                .map_or(FileIntoTarget::Create, |mailbox| {
                    FileIntoTarget::Mailbox(mailbox.document_id)
                }))
        } else {
            self.answer(&request.path)
                .ok_or(Unresolved::Query(&request.path))
                .map(|document_id| FileIntoTarget::Mailbox(document_id.unwrap_or(INBOX_ID)))
        }
    }

    fn file_into(
        &mut self,
        mailbox_id: u32,
        flags: Vec<Keyword>,
        message_id: usize,
        is_file_into: bool,
    ) {
        if let Some(message) = self.messages.get_mut(message_id) {
            message.flags = flags;
            if !message.file_into.contains(&mailbox_id) {
                message.file_into.push(mailbox_id);
            }
            message.did_file_into |= is_file_into;
            self.do_deliver = true;
        } else {
            trc::event!(
                Sieve(SieveEvent::UnexpectedError),
                Details = "Unknown message id.",
                MessageId = message_id,
                SpanId = self.session_id
            );
        }
    }

    fn send_message(
        &mut self,
        source: MessageSource,
        recipient: Recipient<'_>,
        notify: Notify,
        message_id: usize,
    ) {
        let (sender_address, return_path) = if source == MessageSource::Vacation {
            ("", AutogeneratedReturnPath::Null)
        } else {
            (self.mail_from, AutogeneratedReturnPath::Account)
        };
        let Some(message) = self.messages.get(message_id) else {
            trc::event!(
                Sieve(SieveEvent::UnexpectedError),
                Details = "Unknown message id.",
                MessageId = message_id,
                SpanId = self.session_id
            );
            return;
        };

        if self.received_headers >= self.max_received_headers {
            trc::event!(
                Smtp(SmtpEvent::LoopDetected),
                From = CompactString::from(self.mail_from),
                Total = self.received_headers,
                Limit = self.max_received_headers,
                SpanId = self.session_id,
            );
            return;
        }

        let recipients: Vec<String> = match recipient {
            Recipient::Address(rcpt) => vec![rcpt.to_string()],
            Recipient::Group(rcpts) => rcpts.iter().map(|rcpt| rcpt.to_string()).collect(),
            Recipient::List(_) => return,
        };

        if message.raw_message.len() > self.mail_max_size {
            trc::event!(
                Sieve(SieveEvent::MessageTooLarge),
                From = CompactString::from(self.mail_from),
                To = recipients
                    .iter()
                    .map(|r| trc::Value::String(r.as_str().into()))
                    .collect::<Vec<_>>(),
                Size = message.raw_message.len(),
                Limit = self.mail_max_size,
                SpanId = self.session_id,
            );
            return;
        }

        trc::event!(
            Sieve(SieveEvent::SendMessage),
            From = CompactString::from(sender_address),
            To = recipients
                .iter()
                .map(|r| trc::Value::String(r.as_str().into()))
                .collect::<Vec<_>>(),
            Size = message.raw_message.len(),
            SpanId = self.session_id
        );

        let mut raw_message = Vec::with_capacity(160 + message.raw_message.len());
        write_received_header(&mut raw_message, self.server_name, self.session_id);
        raw_message.extend_from_slice(message.raw_message.as_ref());

        if source == MessageSource::Redirect {
            self.redirect_copies += recipients.len();
        }
        self.autogenerated.push(AutogeneratedMessage {
            account_address: self.mail_from.to_string(),
            return_path,
            recipients,
            message: raw_message,
            notify,
            source,
            exploded: false,
        });
        self.do_redirect = true;
    }
}

fn keywords(flags: &[&str]) -> Vec<Keyword> {
    flags
        .iter()
        .filter_map(|flag| {
            Keyword::try_parse(flag)
                .or_else(|| Keyword::is_atom(flag.as_bytes()).then(|| Keyword::from_str(flag)))
        })
        .collect()
}

impl<'x> Handler<'x> for SieveHandler<'x, '_> {
    fn include_script(
        &mut self,
        _: &Context<'x>,
        name: Script<'_>,
        optional: bool,
    ) -> Reply<Option<&'x Sieve<'x>>> {
        match name {
            Script::Personal(name) => {
                self.pending = Some(PendingWork::Include {
                    name: name.to_string(),
                });
                Reply::Pending
            }
            Script::Global(name) => Reply::Ready(if optional {
                self.server.core.sieve.untrusted_script(name)
            } else {
                self.server
                    .get_untrusted_sieve_script(name, self.session_id)
            }),
        }
    }

    fn mailbox_exists(
        &mut self,
        _: &Context<'x>,
        mailboxes: &[Mailbox<'_>],
        special_use: &[&str],
    ) -> Reply<bool> {
        let request = MailboxExistsRequest {
            mailboxes: mailboxes
                .iter()
                .map(|mailbox| match mailbox {
                    Mailbox::Name(name) => Some(MailboxQuery::Path((*name).into())),
                    Mailbox::Id(id) => MailboxQuery::from_id(id),
                })
                .collect(),
            roles: special_use
                .iter()
                .map(|role| MailboxQuery::from_role(role))
                .collect(),
        };

        match self.mailbox_exists_answer(&request).ok() {
            Some(exists) => Reply::Ready(exists),
            None => {
                self.pending = Some(PendingWork::MailboxExists(request));
                Reply::Pending
            }
        }
    }

    fn duplicate_id(&mut self, _: &Context<'x>, id: &str, expiry: u64, last: bool) -> Reply<bool> {
        if expiry == 0 {
            return Reply::Ready(false);
        }

        let hash = SeenIdHash::new(self.script_hash, id);
        match self.checked_ids.get(&hash) {
            Some(result) => Reply::Ready(*result),
            None => {
                self.pending = Some(PendingWork::DuplicateId { hash, expiry, last });
                Reply::Pending
            }
        }
    }

    fn function(
        &mut self,
        _: &Context<'x>,
        id: u32,
        arguments: &[Variable<'x>],
    ) -> Reply<Variable<'x>> {
        self.pending = Some(PendingWork::Function {
            id,
            arguments: arguments.to_vec(),
        });
        Reply::Pending
    }

    fn action(&mut self, _: &Context<'x>, action: SieveAction<'_>) -> Reply<()> {
        match action {
            SieveAction::Keep { flags, message_id } => {
                let flags = keywords(flags);
                self.file_into(INBOX_ID, flags, message_id, false);
            }
            SieveAction::Discard => {
                self.do_discard = true;
            }
            SieveAction::Reject { reason, .. } => {
                self.reject_reason = reason.to_string().into();
                self.do_discard = true;
            }
            SieveAction::FileInto {
                folder,
                flags,
                mailbox_id,
                special_use,
                create,
                message_id,
            } => {
                let request = FileIntoRequest {
                    path: MailboxQuery::Path(folder.into()),
                    mailbox_id: mailbox_id.and_then(MailboxQuery::from_id),
                    special_use: special_use.and_then(MailboxQuery::from_role),
                    create,
                    flags: keywords(flags),
                    message_id,
                };
                match self.file_into_target(&request).ok() {
                    Some(FileIntoTarget::Mailbox(target_id)) => {
                        self.file_into(target_id, request.flags, message_id, true)
                    }
                    _ => {
                        self.pending = Some(PendingWork::FileInto(request));
                        return Reply::Pending;
                    }
                }
            }
            SieveAction::SendMessage {
                source,
                recipient,
                notify,
                message_id,
                ..
            } => {
                self.send_message(source, recipient, notify, message_id);
            }
            SieveAction::CreatedMessage { message, .. } => {
                self.messages.push(SieveMessage {
                    raw_message: message.into(),
                    file_into: Vec::new(),
                    did_file_into: false,
                    flags: Vec::new(),
                });
            }
            SieveAction::Notify { .. } | SieveAction::SetEnvelope { .. } => (),
        }

        Reply::Ready(())
    }
}

