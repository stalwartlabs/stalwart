pub(crate) async fn queued_message_set(
    mut set: RegistrySetResponse<'_>,
) -> trc::Result<RegistrySetResponse<'_>> {
    // Fail all create operations
    set.fail_all_create("Queued messages cannot be created");

    // SPDX-SnippetBegin
    // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
    // SPDX-License-Identifier: LicenseRef-SEL
    #[cfg(feature = "enterprise")]
    let tenant_id = set.access_token.tenant_id();
    // SPDX-SnippetEnd

    // Process update operations
    let mut refresh_queues = QueueNames::default();
    'outer: for (id, value) in set.update.drain(..) {
        let queue_id = id.id();
        let Some(archive) = set.server.read_message_archive(queue_id).await? else {
            set.response.not_updated.append(id, SetError::not_found());
            continue;
        };
        let archived_message = archive.to_unarchived::<Message>()?;
        // SPDX-SnippetBegin
        // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
        // SPDX-License-Identifier: LicenseRef-SEL
        #[cfg(feature = "enterprise")]
        if tenant_id.is_some_and(|tenant_id| !archived_message.inner.has_tenant(tenant_id)) {
            set.response.not_updated.append(id, SetError::not_found());
            continue;
        }
        // SPDX-SnippetEnd

        // Process patches
        let mut message = map_message(archived_message.inner, queue_id);
        message.next_retry = None;
        for (key, value) in value.into_expanded_object() {
            let ptr = match key {
                Key::Property(prop) => {
                    JsonPointer::new(vec![JsonPointerItem::Key(Key::Property(prop))])
                }
                Key::Borrowed(other) => JsonPointer::parse(other),
                Key::Owned(other) => JsonPointer::parse(&other),
            };
            if let Err(err) = message.patch(JsonPointerPatch::new(&ptr).with_create(false), value) {
                set.response.not_updated.append(id, err.into());
                continue 'outer;
            }
        }
        let set_next_retry = message.next_retry;

        // Process changes
        let mut has_changes = false;
        let mut modified_rcpts = AHashSet::new();
        let mut queued_message = archived_message.deserialize()?;
        let prev_events = queued_message.next_events();
        if queued_message.env_id.as_deref() != message.env_id.as_deref() {
            queued_message.env_id = message.env_id.as_deref().map(|v| v.into());
            has_changes = true;
        }
        if queued_message.priority as i64 != message.priority {
            queued_message.priority = message.priority as i16;
            has_changes = true;
        }
        for (idx, rcpt) in queued_message.recipients.iter_mut().enumerate() {
            if !message
                .recipients
                .iter()
                .any(|(address, _)| address.as_str() == rcpt.address.as_ref())
            {
                rcpt.status = Status::PermanentFailure(Box::new(ErrorDetails {
                    entity: "localhost".into(),
                    details: queue::Error::Io("Delivery canceled.".into()),
                }));
                has_changes = true;
                modified_rcpts.insert(idx);
            }
        }
        for (address, rcpt) in message.recipients.into_iter() {
            let Some((idx, queued_rcpt)) = queued_message
                .recipients
                .iter_mut()
                .enumerate()
                .find(|(_, r)| r.address.as_ref() == address.as_str())
            else {
                set.response.not_updated.append(
                    id,
                    SetError::invalid_properties()
                        .with_description(format!("Recipient '{address}' does not exist")),
                );
                continue 'outer;
            };
            let mut changed = false;
            if rcpt.orcpt.as_deref() != queued_rcpt.orcpt.as_deref() {
                queued_rcpt.orcpt = rcpt.orcpt.as_deref().map(|v| v.into());
                changed = true;
            }
            let expiry = match rcpt.expires {
                QueueExpiry::Ttl(ttl) => common::config::smtp::queue::QueueExpiry::Ttl(
                    (ttl.expires_at.timestamp() as u64).saturating_sub(queued_message.created),
                ),
                QueueExpiry::Attempts(attempts) => {
                    common::config::smtp::queue::QueueExpiry::Attempts(
                        attempts.expires_attempts as u32,
                    )
                }
            };
            if expiry != queued_rcpt.expires {
                queued_rcpt.expires = expiry;
                changed = true;
            }

            for (due, count, field) in [
                (rcpt.retry_due, rcpt.retry_count, &mut queued_rcpt.retry),
                (rcpt.notify_due, rcpt.notify_count, &mut queued_rcpt.notify),
            ] {
                let schedule = Schedule {
                    due: due.timestamp() as u64,
                    inner: count as u32,
                };
                if schedule != *field {
                    *field = schedule;
                    changed = true;
                }
            }

            if let Some(next_retry) = set_next_retry
                && !matches!(queued_rcpt.status, Status::PermanentFailure(_))
            {
                let new_due = next_retry.timestamp() as u64;
                if queued_rcpt.retry.due != new_due {
                    queued_rcpt.retry.due = new_due;
                    changed = true;
                }
            }

            if matches!(rcpt.status, RecipientStatus::Scheduled)
                && !matches!(queued_rcpt.status, Status::Scheduled)
            {
                queued_rcpt.status = Status::Scheduled;
                changed = true;
            }

            if changed {
                has_changes = true;
                modified_rcpts.insert(idx);
            }
        }

        if has_changes {
            // Delete message if there are no pending deliveries
            let message = MessageWrapper::new(queued_message, queue_id, QueueName::default());
            let queues = message
                .message
                .recipients
                .iter()
                .map(|rcpt| rcpt.queue)
                .collect::<QueueNames>();
            let status = if message.message.recipients.iter().any(|recipient| {
                matches!(
                    recipient.status,
                    Status::TemporaryFailure(_) | Status::Scheduled
                )
            }) {
                message
                    .save_registry_changes(set.server, prev_events, modified_rcpts)
                    .await
            } else {
                message
                    .remove_registry(set.server, prev_events, archive.version)
                    .await
            };

            if let Some(description) = status.failure("Queue update operation failed") {
                set.response
                    .not_updated
                    .append(id, SetError::forbidden().with_description(description));
                continue;
            }

            refresh_queues.merge(&queues);
        }

        set.response.updated.append(id, None);
    }

    if !refresh_queues.is_empty() {
        let _ = set
            .server
            .inner
            .ipc
            .queue_tx
            .send(QueueEvent::Refresh(QueueRefresh::Queues(refresh_queues)))
            .await;
    }

    // Process destroy operations
    for id in set.destroy.drain(..) {
        let Some((message, version)) = set
            .server
            .read_message_versioned(id.id(), QueueName::default())
            .await
        else {
            set.response.not_destroyed.append(id, SetError::not_found());
            continue;
        };

        // SPDX-SnippetBegin
        // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
        // SPDX-License-Identifier: LicenseRef-SEL
        #[cfg(feature = "enterprise")]
        if tenant_id.is_some_and(|tenant_id| !message.message.has_tenant(tenant_id)) {
            set.response.not_destroyed.append(id, SetError::not_found());
            continue;
        }
        // SPDX-SnippetEnd

        let prev_events = message.message.next_events();
        match message
            .remove_registry(set.server, prev_events, version)
            .await
            .failure("Queue delete operation failed")
        {
            None => set.response.destroyed.push(id),
            Some(description) => set
                .response
                .not_destroyed
                .append(id, SetError::forbidden().with_description(description)),
        }
    }

    Ok(set)
}

pub(crate) async fn queued_message_get(
    mut get: RegistryGetResponse<'_>,
) -> trc::Result<RegistryGetResponse<'_>> {
    let client_ids = get.ids.is_some();
    let ids = if let Some(ids) = get.ids.take() {
        ids
    } else {
        queued_ids(get.server, get.server.core.jmap.get_max_objects)
            .await?
            .into_iter()
            .map(Id::from)
            .collect()
    };

    // SPDX-SnippetBegin
    // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
    // SPDX-License-Identifier: LicenseRef-SEL
    #[cfg(feature = "enterprise")]
    let tenant_id = get.access_token.tenant_id();
    // SPDX-SnippetEnd

    for id in ids {
        let Some(message_archive) = get.server.read_message_archive(id.id()).await? else {
            if client_ids {
                get.not_found(id);
            }
            continue;
        };
        let message_in = message_archive.unarchive::<Message>()?;
        // SPDX-SnippetBegin
        // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
        // SPDX-License-Identifier: LicenseRef-SEL
        #[cfg(feature = "enterprise")]
        if tenant_id.is_some_and(|tenant_id| !message_in.has_tenant(tenant_id)) {
            if client_ids {
                get.not_found(id);
            }
            continue;
        }
        // SPDX-SnippetEnd
        get.insert(id, map_message(message_in, id.id()).into_value());
    }

    Ok(get)
}

pub(crate) async fn queued_message_query(
    mut req: RegistryQueryResponse<'_>,
) -> trc::Result<QueryResponseBuilder> {
    let mut due_from = 0u64;
    let mut due_to = u64::MAX;
    let mut queue_name = None;
    let mut filter_text = None;
    let mut filter_from = None;
    let mut filter_to = None;

    // SPDX-SnippetBegin
    // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
    // SPDX-License-Identifier: LicenseRef-SEL
    #[cfg(feature = "enterprise")]
    let tenant_id = req.access_token.tenant_id();
    // SPDX-SnippetEnd
    #[cfg(not(feature = "enterprise"))]
    let tenant_id: Option<u32> = None;

    req.request
        .extract_filters(|property, op, value| match property {
            Property::Due => {
                if let Some(due) = value.as_str().and_then(|s| UTCDateTime::from_str(s).ok()) {
                    let due = due.timestamp() as u64;
                    let (from, to) = match op {
                        RegistryFilterOp::Equal => (due, due),
                        RegistryFilterOp::GreaterThan => (due + 1, u64::MAX),
                        RegistryFilterOp::GreaterEqualThan => (due, u64::MAX),
                        RegistryFilterOp::LowerThan => (0, due - 1),
                        RegistryFilterOp::LowerEqualThan => (0, due),
                        _ => return false,
                    };

                    // Intersect with existing range
                    due_from = due_from.max(from);
                    due_to = due_to.min(to);

                    due_from <= due_to
                } else {
                    false
                }
            }
            Property::QueueName => {
                if let Some(value) = value.as_str().and_then(QueueName::new) {
                    queue_name = Some(value);
                    true
                } else {
                    false
                }
            }
            Property::ReturnPath => {
                if let serde_json::Value::String(name) = value {
                    filter_from = Some(name);
                    true
                } else {
                    false
                }
            }
            Property::To => {
                if let serde_json::Value::String(name) = value {
                    filter_to = Some(name);
                    true
                } else {
                    false
                }
            }
            Property::Text => {
                if let serde_json::Value::String(name) = value {
                    filter_text = Some(name);
                    true
                } else {
                    false
                }
            }
            _ => false,
        })?;

    if req
        .request
        .sort
        .as_ref()
        .and_then(|sort| sort.first())
        .is_some_and(|comp| !matches!(comp.property, RegistryComparator::Property(Property::Due)))
    {
        return Err(trc::JmapEvent::UnsupportedSort
            .into_err()
            .details("Only sorting by 'due' is supported for queued messages"));
    }

    let params = req
        .request
        .extract_parameters(req.server.core.jmap.query_max_results, None)?;

    let has_filters = filter_text.is_some() || filter_from.is_some() || filter_to.is_some();
    if has_filters {
        let mut results = Vec::with_capacity(8);
        let mut collect = |key: &[u8], value: &[u8]| {
            let message_ = <Archive<ArchiveBytes> as Deserialize>::deserialize(value)
                .add_context(|ctx| ctx.ctx(trc::Key::Key, key))?;
            let message = message_
                .unarchive::<queue::Message>()
                .add_context(|ctx| ctx.ctx(trc::Key::Key, key))?;

            if let Some(due) = message.next_delivery_event(queue_name)
                && (due_from..=due_to).contains(&due)
                && queue_name
                    .as_ref()
                    .is_none_or(|q| message.recipients.iter().any(|r| &r.queue == q))
                && filter_text
                    .as_ref()
                    .map(|text| {
                        message.return_path.contains(text)
                            || message
                                .recipients
                                .iter()
                                .any(|r| r.address().contains(text))
                    })
                    .unwrap_or_else(|| {
                        filter_from
                            .as_ref()
                            .is_none_or(|from| message.return_path.contains(from))
                            && filter_to.as_ref().is_none_or(|to| {
                                message.recipients.iter().any(|r| r.address().contains(to))
                            })
                    })
            {
                results.push((key.deserialize_be_u64(0)?, due));
            }

            Ok(true)
        };

        match tenant_id {
            // SPDX-SnippetBegin
            // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
            // SPDX-License-Identifier: LicenseRef-SEL
            #[cfg(feature = "enterprise")]
            Some(tenant_id) => {
                iterate_tenant_messages(req.server, tenant_id, &mut collect).await?;
            }
            // SPDX-SnippetEnd
            _ => {
                req.server
                    .store()
                    .iterate(
                        IterateParams::new(
                            ValueKey::from(ValueClass::Queue(QueueClass::Message(0))),
                            ValueKey::from(ValueClass::Queue(QueueClass::Message(u64::MAX))),
                        )
                        .ascending(),
                        &mut collect,
                    )
                    .await
                    .caused_by(trc::location!())?;
            }
        }

        // Build response
        let mut response = QueryResponseBuilder::new(
            results.len(),
            req.server.core.jmap.query_max_results,
            State::Initial,
            &req.request,
        );

        if params.sort_ascending {
            results.sort_by_key(|(_, due)| *due);
        } else {
            results.sort_by_key(|(_, due)| u64::MAX - *due);
        }

        for (id, _) in results {
            if !response.add_id(id.into()) {
                break;
            }
        }

        Ok(response)
    } else {
        // Build response
        let mut response = QueryResponseBuilder::new(
            req.server.core.jmap.query_max_results,
            req.server.core.jmap.query_max_results,
            State::Initial,
            &req.request,
        );

        let mut total = 0;
        if let Some(anchor) = req.request.anchor {
            let anchor_id = anchor.id();
            if let Some(archive) = req.server.read_message_archive(anchor_id).await?
                && let Ok(archived) = archive.unarchive::<Message>()
                && let Some(anchor_due) = archived.next_event(queue_name)
                && anchor_due >= due_from
                && anchor_due <= due_to
            {
                if params.sort_ascending {
                    due_from = anchor_due;
                } else {
                    due_to = anchor_due;
                }
            }
        }

        let page = req
            .request
            .anchor
            .is_none()
            .then(|| query_page(&req.request, &response))
            .flatten();
        let count_total = response.response.total.is_some();
        let mut entries = Vec::new();
        match tenant_id {
            // SPDX-SnippetBegin
            // SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
            // SPDX-License-Identifier: LicenseRef-SEL
            #[cfg(feature = "enterprise")]
            Some(tenant_id) => {
                iterate_tenant_messages(req.server, tenant_id, |key, value| {
                    let message_ = <Archive<ArchiveBytes> as Deserialize>::deserialize(value)
                        .add_context(|ctx| ctx.ctx(trc::Key::Key, key))?;
                    let message = message_
                        .unarchive::<queue::Message>()
                        .add_context(|ctx| ctx.ctx(trc::Key::Key, key))?;
                    let queue_id = key.deserialize_be_u64(0)?;
                    let mut push = |queue_name| {
                        if let Some(due) = message.next_event(Some(queue_name))
                            && (due_from..=due_to).contains(&due)
                        {
                            entries.push((due, queue_id));
                        }
                    };
                    if let Some(queue_name) = queue_name {
                        push(queue_name);
                    } else {
                        for queue_name in message
                            .recipients
                            .iter()
                            .filter_map(|rcpt| QueueName::from_bytes(rcpt.queue.as_slice()))
                            .collect::<QueueNames>()
                            .iter()
                        {
                            push(queue_name);
                        }
                    }
                    Ok(true)
                })
                .await?;
            }
            // SPDX-SnippetEnd
            _ => {
                if let Some(queue_name) = queue_name {
                    let mut iterate = IterateParams::new(
                        queue_event_key(queue_name, due_from, 0),
                        queue_event_key(queue_name, due_to, u64::MAX),
                    )
                    .set_ascending(params.sort_ascending)
                    .no_values();
                    if let Some(page) = page
                        && !count_total
                    {
                        iterate = iterate.limit(page);
                    }

                    req.server
                        .store()
                        .iterate(iterate, |key, _| {
                            let event = store::write::QueueEvent::deserialize(key)?;
                            entries.push((event.due, event.queue_id));
                            Ok(count_total || page.is_none_or(|page| entries.len() < page))
                        })
                        .await
                        .caused_by(trc::location!())?;
                } else {
                    let read_limit = match page {
                        Some(page) if !count_total => page.saturating_add(1),
                        _ => LISTING_READ_LIMIT,
                    };
                    let mut current = None;
                    let mut taken = 0;
                    walk_queues(
                        req.server.store(),
                        QueueWalk {
                            due_from,
                            due_to,
                            ascending: params.sort_ascending,
                            read_limit,
                        },
                        |event| {
                            if current != Some(event.queue_name) {
                                current = Some(event.queue_name);
                                taken = 0;
                            }
                            entries.push((event.due, event.queue_id));
                            taken += 1;
                            if count_total || page.is_none_or(|page| taken < page) {
                                WalkStep::Continue
                            } else {
                                WalkStep::NextQueue
                            }
                        },
                    )
                    .await?;
                }
            }
        }

        if params.sort_ascending {
            entries.sort_unstable();
        } else {
            entries.sort_unstable_by(|a, b| b.cmp(a));
        }
        let mut seen_ids = AHashSet::with_capacity(entries.len());
        for (_, id) in entries {
            if seen_ids.insert(id) {
                total += 1;
                if count_total {
                    if !response.is_full() {
                        response.add_id(id.into());
                    }
                } else if !response.add_id(id.into()) {
                    break;
                }
            }
        }

        if response.response.total.is_some() {
            response.response.total = Some(total);
        }

        if let Some(limit) = response.response.limit
            && total < limit
        {
            response.response.limit = None;
        }

        Ok(response)
    }
}

fn queue_event_key(queue_name: QueueName, due: u64, queue_id: u64) -> ValueKey<ValueClass> {
    ValueKey::from(ValueClass::Queue(QueueClass::MessageEvent(
        store::write::QueueEvent {
            due,
            queue_id,
            queue_name: queue_name.into_inner(),
        },
    )))
}

// SPDX-SnippetBegin
// SPDX-FileCopyrightText: 2020 Stalwart Labs LLC <hello@stalw.art>
// SPDX-License-Identifier: LicenseRef-SEL
#[cfg(feature = "enterprise")]
async fn iterate_tenant_messages(
    server: &Server,
    tenant_id: u32,
    cb: impl for<'x> FnMut(&'x [u8], &'x [u8]) -> trc::Result<bool> + Sync + Send,
) -> trc::Result<()> {
    let tenant_key = |queue_id| {
        ValueKey::from(ValueClass::Queue(QueueClass::TenantMessage {
            tenant_id,
            queue_id,
        }))
    };
    let mut messages = Vec::new();
    server
        .store()
        .iterate(
            IterateParams::new(tenant_key(0), tenant_key(u64::MAX)).no_values(),
            |key, _| {
                let key = ValueKey::from(ValueClass::Queue(QueueClass::Message(
                    store::write::QueueEvent::deserialize(key)?.queue_id,
                )));
                messages.push(IterateParams::new(key.clone(), key));
                Ok(true)
            },
        )
        .await
        .caused_by(trc::location!())?;

    if messages.is_empty() {
        Ok(())
    } else {
        server
            .store()
            .iterate_many(messages, cb)
            .await
            .caused_by(trc::location!())
    }
}
